// docs/url-map.csv -> public/.htaccess (Apache and LiteSpeed on Hostinger).
// Built on the proven ../website_old/.htaccess. Run by `pnpm build` before astro build.
// Every rule is one hop. THE_REQUEST guards stop internal rewrites from being redirected again.
import { readFileSync, writeFileSync } from 'node:fs';
import { parseCsv } from './csv.mjs';

// Two English posts rank at their root URL; their /en twin is a one-hop 301 back (src/english-root.json).
const englishRoot = JSON.parse(readFileSync('src/english-root.json', 'utf8'));

const HOST = 'lulwa.com.sa';
const CMS_MOVED = false; // set true once cms.lulwa.com.sa has DNS and SSL: lulwa.com.sa/cms then 301s there
const rows = parseCsv(readFileSync('docs/url-map.csv', 'utf8')).map(([old_path = '', action = '', target = '']) => ({ old_path, action, target }));

for (const row of rows) {
  if (!['keep', '301', '410'].includes(row.action)) throw new Error(`url-map: unknown action "${row.action}" for ${row.old_path}`);
  if (row.action === 'keep' && row.target !== row.old_path) throw new Error(`url-map: keep row ${row.old_path} must target itself`);
}

const esc = (path) => path.replace(/^\//, '').replace(/[.]/g, '\\.');

// Rows other than keep (none today). 301 and 410 stay supported so a page can be retired later without editing this file.
const mapped = rows
  .filter((r) => r.action !== 'keep')
  .map((r) => (r.action === '410' ? `RewriteRule ^${esc(r.old_path)}(?:\\.html)?/?$ - [G,L,NE]` : `RewriteRule ^${esc(r.old_path)}(?:\\.html)?/?$ ${r.target} [R=301,L,NE]`));

// Old Arabic-slug URLs (/ar/...) to their root equivalents. /en is a real page now, so there is no /en rule.
const SUFFIX = '(?:\\.html)?/?$';
const arabic = [
  ['من-نحن', '/about'],
  ['اتصل-بنا', '/contact'],
  ['سياسة-الخصوصية', '/privacy-policy'],
  ['شروط-الخدمة', '/terms-of-service'],
  ['سياسة-ملفات-التعريف-الارتباط', '/cookie-policy'],
  ['خدمات', '/services'],
  ['ماركات', '/brands'],
  ['المناطق', '/areas'],
  ['خدمات/إصلاح-المكيفات', '/services/ac-repair'],
  ['خدمات/إصلاح-غسالات-الصحون', '/services/dishwasher-repair'],
  ['خدمات/إصلاح-النشافات', '/services/dryer-repair'],
  ['خدمات/إصلاح-الفريزرات', '/services/freezer-repair'],
  ['خدمات/إصلاح-الميكروويف', '/services/microwave-repair'],
  ['خدمات/إصلاح-الأفران-والموقد', '/services/oven-stove-repair'],
  ['خدمات/إصلاح-الثلاجات', '/services/refrigerator-repair'],
  ['خدمات/إصلاح-الغسالات', '/services/washing-machine-repair'],
  ['خدمات/إصلاح-سخانات-الماء', '/services/water-heater-repair'],
].map(([from, to]) => `RewriteRule ^ar/${from}${SUFFIX} ${to} [R=301,L,NE]`);
// Pages under the three Arabic folders go to the same slug under the root folder.
const arabicChildren = [['خدمات', 'services'], ['ماركات', 'brands'], ['المناطق', 'areas']].map(([from, to]) => `RewriteRule ^ar/${from}/(.+?)${SUFFIX} /${to}/$1 [R=301,L,NE]`);

const caseFix = ['services', 'areas', 'brands'].flatMap((s) => {
  const S = s[0].toUpperCase() + s.slice(1);
  // Case-SENSITIVE guard (no NC on the condition): a correct lowercase URL must never match, or it would redirect to itself forever.
  return [
    `RewriteCond %{REQUEST_URI} !^/${s}(?:/|$)`,
    `RewriteRule ^${S}/?$ /${s} [R=301,L,NC,NE]`,
    `RewriteCond %{REQUEST_URI} !^/${s}(?:/|$)`,
    `RewriteRule ^${S}/(.+)$ /${s}/$1 [R=301,L,NC,NE]`,
  ];
});

const rootSlug = ['services', 'areas', 'brands'].flatMap((s) => [
  'RewriteCond %{REQUEST_FILENAME} !-f',
  'RewriteCond %{REQUEST_FILENAME} !-d',
  `RewriteCond %{DOCUMENT_ROOT}/$1${s}/$2.html -f`,
  `RewriteRule ^(en/)?([a-z0-9][a-z0-9-]*)(?:\\.html)?$ /$1${s}/$2 [R=301,L,NE]`,
]);

const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://www.clarity.ms https://*.clarity.ms https://www.google-analytics.com",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: https://www.google-analytics.com https://*.google-analytics.com https://www.googletagmanager.com https://*.googletagmanager.com https://*.clarity.ms https://c.bing.com",
  "font-src 'self'",
  "connect-src 'self' https://www.google-analytics.com https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com https://*.googletagmanager.com https://*.clarity.ms https://c.bing.com",
  'frame-src https://www.google.com https://www.googletagmanager.com',
  "form-action 'self'",
  "base-uri 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'",
].join('; ');

const text = `#############################################
# Generated by scripts/redirects.mjs from docs/url-map.csv. Do not edit by hand.
# Lulwa static site, Hostinger (LiteSpeed or Apache). Canonical host: https://${HOST}
# Public URLs have no .html and no trailing slash (the site root "/" excepted).
# /en and /en/* are real pages served from en/. Arabic is the default language at the root.
#############################################

Options -Indexes -MultiViews
DirectorySlash Off
DirectoryIndex index.html

# 404 for the whole site. English 404s under /en/ are answered by error-en.php (see the end of the rewrite section).
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # The blog CMS subdomain (docroot public_html/cms) skips every root rule below.
  RewriteCond %{HTTP_HOST} ^cms\\.lulwa\\.com\\.sa$ [NC]
  RewriteRule ^ - [L]
${CMS_MOVED ? '  RewriteRule ^cms(?:/(.*))?$ https://cms.lulwa.com.sa/$1 [R=301,L,NE]\n' : ''}
  ###########################################
  # 1) Block hidden, system and private files (.well-known stays open)
  ###########################################
  RewriteRule "(^|/)\\.(?!well-known(?:/|$))" - [F,L]
  RewriteRule "(?:^|/)(?:.*\\.(?:bak|config|dist|env|fla|ini|log|md|ps1|py|sh|sql|swp|tmp|ya?ml)|composer\\.(?:json|lock)|package(?:-lock)?\\.json|pnpm-lock\\.yaml|yarn\\.lock)$" - [F,L,NC]
  RewriteRule ^(?:config|includes|database|logs)/ - [F,L,NC]
  RewriteRule \\.(?:test|orig|old)$ - [G,L,NC]

  # Old admin and analytics endpoints are gone. Any .php other than the form handler, the English 404 and the blog CMS sign-in is gone.
  RewriteRule ^admin(?:/|$) - [G,L,NC]
  RewriteRule ^api(?:/|$) - [G,L,NC]
  RewriteRule ^(?!contact-submit\\.php$|error-en\\.php$|cms/auth\\.php$).*\\.php$ - [G,L,NC]

  # Hashed build files and fonts are cached for a year (the Header rules below read this flag).
  RewriteRule ^(?:_astro|fonts)/ - [E=LULWA_IMMUTABLE:1]

  ###########################################
  # 2) Canonical host and HTTPS, one hop. localhost is left alone so tests run.
  ###########################################
  RewriteCond %{HTTP_HOST} ^(?:www\\.)?automaticwashingmachine\\.com$ [NC]
  RewriteRule ^ https://${HOST}/services/washing-machine-repair [R=301,L,NE]

  RewriteCond %{HTTP_HOST} !^${HOST.replace(/\./g, '\\.')}$ [NC]
  RewriteCond %{HTTP_HOST} !^(?:localhost|127\\.0\\.0\\.1|\\[::1\\])(?::\\d+)?$ [NC]
  RewriteRule ^ https://${HOST}%{REQUEST_URI} [R=301,L,NE]

  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP_HOST} ^${HOST.replace(/\./g, '\\.')}$ [NC]
  RewriteRule ^ https://${HOST}%{REQUEST_URI} [R=301,L,NE]

  ###########################################
  # 3) Repeated slashes
  ###########################################
  RewriteRule ^(.+)//+(.+)$ /$1/$2 [R=301,L,NE]
  # Apache merges slashes before the rule above sees the path, so the request line is checked too (the merged path is the target).
  RewriteCond %{THE_REQUEST} \s[^\s?]*//
  RewriteRule ^(.*)$ /$1 [R=301,L,NE]

  ###########################################
  # 4) Old Arabic-slug URLs (/ar/...) to the root pages
  ###########################################
  RewriteRule ^ar(?:/index(?:\\.html)?)?/?$ / [R=301,L,NE]
${[...arabic, ...arabicChildren].map((l) => `  ${l}`).join('\n')}
  RewriteRule ^ar/(.+?)(?:\\.html)?/?$ /$1 [R=301,L,NE]

  ###########################################
  # 5) Case fixes for /Services /Areas /Brands
  ###########################################
${caseFix.map((l) => `  ${l}`).join('\n')}

  ###########################################
  # 5b) /faults and /faults/<slug> were preview-only pages; their answers are sections of the service pages now.
  #     Placed before 6) so /faults/index.html is also one hop.
  ###########################################
  RewriteRule ^(en/)?faults(?:\\.html|/.*)?$ /$1services [R=301,L,NE]

  ###########################################
  # 6) index and index.html to the folder URL.
  #    THE_REQUEST holds the original request line, so an internal rewrite to index.html is never redirected back (that was a loop).
  ###########################################
  RewriteCond %{THE_REQUEST} \\s/+(?:[^\\s?]*/)?index(?:\\.html)?(?:[\\s?]|$) [NC]
  RewriteRule ^(?:(.*)/)?index(?:\\.html)?$ /$1 [R=301,L,NE]

  ###########################################
  # 7) Retired pages and pages that moved
  ###########################################
  RewriteRule ^(en/)?blog/(?:category|tag)(?:/.*)?$ /$1blog [R=301,L,NE]
  RewriteRule ^(en/)?blog/search/?$ /$1blog [R=301,L,NE]
${englishRoot.map((p) => `  RewriteRule ^en/${esc(p)}(?:[.]html)?/?$ ${p} [R=301,L,NE]`).join('\n')}
  RewriteRule ^(?:offline|500)(?:\\.html)?/?$ / [R=301,L,NE]
${mapped.map((l) => `  ${l}`).join('\n')}

  ###########################################
  # 8) Root-slug safety net: /ac-repair, /lg-appliance-repair and so on go to the real page, in one hop (.html form included)
  ###########################################
${rootSlug.map((l) => `  ${l}`).join('\n')}

  ###########################################
  # 9) Strip .html from public URLs (one 301; the 404 page is exempt)
  ###########################################
  RewriteCond %{THE_REQUEST} \\s/+[^?\\s]*\\.html(?:[\\s?]|$) [NC]
  RewriteCond %{REQUEST_URI} !^/(?:en/)?404\\.html$
  RewriteRule ^(.+)\\.html$ /$1 [R=301,L,NE]

  ###########################################
  # 10) Trailing slash off, except the root
  ###########################################
  RewriteCond %{REQUEST_URI} !^/$
  RewriteRule ^(.+)/$ /$1 [R=301,L,NE]

  ###########################################
  # 11) Internal rewrites: clean URL to the physical file
  #     hubs: services/index.html, en/index.html ...   pages: about.html, services/ac-repair.html ...
  ###########################################
  RewriteRule ^$ index.html [L]

  RewriteCond %{DOCUMENT_ROOT}/$1/index.html -f
  RewriteRule ^([a-z0-9][a-z0-9/_-]*)$ $1/index.html [L]

  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^((?!404$|en/404$)[a-z0-9][a-z0-9/_-]*)$ $1.html [L]

  # Anything left under /en/ that is not a file gets the English 404 (status 404, English page).
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule ^en/ error-en.php [L]
</IfModule>

#############################################
# Security headers
#############################################
<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "accelerometer=(), autoplay=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()"
  # CSP allows Google Tag Manager, GA4 and Microsoft Clarity. Fonts are self-hosted.
  Header always set Content-Security-Policy "${csp}"
  # HSTS only on HTTPS, so a local test over http is not pinned.
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains" env=HTTPS

  <FilesMatch "^(?:404\\.html|error-en\\.php)$">
    Header always set X-Robots-Tag "noindex, noarchive, nosnippet"
  </FilesMatch>
</IfModule>

#############################################
# Compression (LiteSpeed compresses on its own and ignores these; Apache uses them)
#############################################
<IfModule mod_brotli.c>
  AddOutputFilterByType BROTLI_COMPRESS application/rss+xml application/manifest+json text/xml text/html text/plain text/css text/javascript application/javascript application/json application/xml image/svg+xml
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE application/rss+xml application/manifest+json text/xml text/html text/plain text/css text/javascript application/javascript application/json application/xml image/svg+xml
</IfModule>

#############################################
# MIME helpers
#############################################
<IfModule mod_mime.c>
  AddType image/svg+xml .svg .svgz
  AddType application/manifest+json .webmanifest
  AddType image/avif .avif
  AddType font/woff2 .woff2
  AddType image/avif-sequence .avifs
  AddCharset UTF-8 .html .css .js .xml .txt .json .svg
  AddDefaultCharset UTF-8
</IfModule>

#############################################
# Browser caching
#############################################
<IfModule mod_expires.c>
  ExpiresActive On

  ExpiresByType text/html "access plus 0 seconds"
  ExpiresByType application/xhtml+xml "access plus 0 seconds"

  ExpiresByType text/css "access plus 1 week"
  ExpiresByType text/javascript "access plus 1 week"
  ExpiresByType application/javascript "access plus 1 week"

  ExpiresByType image/svg+xml "access plus 6 months"
  ExpiresByType image/webp "access plus 6 months"
  ExpiresByType image/avif "access plus 6 months"
  ExpiresByType image/png "access plus 6 months"
  ExpiresByType image/jpeg "access plus 6 months"
  ExpiresByType image/gif "access plus 6 months"
  ExpiresByType image/x-icon "access plus 6 months"
  ExpiresByType image/vnd.microsoft.icon "access plus 6 months"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType font/woff "access plus 1 year"
  ExpiresByType application/font-woff2 "access plus 1 year"
  ExpiresByType application/font-woff "access plus 1 year"
  ExpiresByType application/xml "access plus 1 day"
  ExpiresByType text/xml "access plus 1 day"
</IfModule>

<IfModule mod_headers.c>
  # Later matching sections win, so the specific ones come last.
  <FilesMatch "\\.(?:css|js)$">
    Header set Cache-Control "public, max-age=604800" env=!LULWA_IMMUTABLE
  </FilesMatch>

  <FilesMatch "\\.(?:svg|webp|avif|png|jpe?g|gif|ico)$">
    Header set Cache-Control "public, max-age=15552000" env=!LULWA_IMMUTABLE
  </FilesMatch>

  <FilesMatch "\\.(?:woff2?|ttf)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>

  # Favicons and the manifest can change, so they refresh daily.
  <FilesMatch "^(?:favicon.*|apple-touch-icon.*\\.png|icon-\\d+\\.png|manifest\\.json|site\\.webmanifest|browserconfig\\.xml)$">
    Header set Cache-Control "public, max-age=86400" env=!LULWA_IMMUTABLE
  </FilesMatch>

  # Pages always revalidate (ETag / Last-Modified), but may sit in the back-forward cache.
  <FilesMatch "\\.html?$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>

  # Hashed build output and fonts: one year, immutable.
  Header set Cache-Control "public, max-age=31536000, immutable" env=LULWA_IMMUTABLE
</IfModule>
`;

writeFileSync('public/.htaccess', text);
console.log(`public/.htaccess written (${rows.length} url-map rows, ${mapped.length} mapped rules)`);
