// docs/url-map.csv -> public/_redirects (301s, one hop), worker/gone.ts (410s) and the Worker-first paths in wrangler.jsonc.
// Cloudflare's _redirects cannot answer 410, so those paths go to the Worker.
import { readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync('docs/url-map.csv', 'utf8').trim().split(/\r?\n/).slice(1).map((l) => l.split(','));
const redirects = [
  'https://www.lulwa.com.sa/* https://lulwa.com.sa/:splat 301',
  // Second domain; applies only once that domain is on this Cloudflare account (docs/FOR-AMEER.md).
  'https://automaticwashingmachine.com/* https://lulwa.com.sa/services/washing-machine-repair 301',
  '/en/ /en 301',
  ...rows.filter(([, a]) => a === '301' || a === 'confirm').map(([from, , to]) => `${from} ${to} 301`),
];
writeFileSync('public/_redirects', `${redirects.join('\n')}\n`);

const gone = rows.filter(([, a]) => a === '410').map(([p]) => p);
writeFileSync('worker/gone.ts', `// Generated by scripts/redirects.mjs from docs/url-map.csv. Do not edit.\nexport const gone = new Set(${JSON.stringify(gone, null, 2)});\n`);

const w = readFileSync('wrangler.jsonc', 'utf8');
writeFileSync('wrangler.jsonc', w.replace(/"run_worker_first": \[[^\]]*\]/, `"run_worker_first": ${JSON.stringify(['/api/*', ...gone])}`));
console.log(`${redirects.length} redirects, ${gone.length} gone`);
